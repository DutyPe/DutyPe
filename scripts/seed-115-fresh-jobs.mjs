async function seedAllFreshJobs() {
  console.log(`Starting processing of ${ALL_FRESH_JOBS.length} jobs...`);

  const now = Date.now();
  const JOB_LIFETIME_MS = 30 * 24 * 60 * 60 * 1000;

  let existingTitlesRaw = [];
  try {
    existingTitlesRaw = JSON.parse(readFileSync(resolve(__dirname, "existing-titles.json"), "utf-8"));
  } catch (e) {
    existingTitlesRaw = [];
  }
  const existingTitles = new Set(existingTitlesRaw.map(t => t.toLowerCase().trim()));

  const newJobs = ALL_FRESH_JOBS.filter(j => !existingTitles.has(j.title.toLowerCase().trim()));
  console.log(`Found ${newJobs.length} strictly unique jobs to insert.`);

  let count = 0;
  const CHUNK_SIZE = 30;

  for (let i = 0; i < newJobs.length; i += CHUNK_SIZE) {
    const chunk = newJobs.slice(i, i + CHUNK_SIZE);
    const batch = db.batch();

    for (let j = 0; j < chunk.length; j++) {
      const item = chunk[j];
      const citySlug = (item.district || "hyd").toLowerCase().replace(/[^a-z0-9]/g, "");
      const catSlug = (item.category || "job").toLowerCase().replace(/[^a-z0-9]/g, "");
      const jobId = `oct_${citySlug}_${catSlug}_${Date.now().toString(36)}_${i + j}_${Math.floor(1000 + Math.random() * 9000)}`;

      const lat = item.lat;
      const lng = item.lng;
      const geohash = encodeGeohash(lat, lng, 9);
      const cell = encodeGeohash(lat, lng, 5);
      const keywords = keywordsOf(item.title, item.companyName, item.area, item.district, item.state, item.category.replace(/_/g, " "));

      // Jitter timestamp across Oct 12, 13, 14 (within last 36 hours)
      const hoursAgo = ((count * 7) % 36) + 2; // 2 to 38 hours ago
      const jobCreatedAt = now - (hoursAgo * 60 * 60 * 1000);

      const cardData = {
        employerId: "admin_dutype",
        title: item.title,
        category: item.category,
        employmentType: item.employmentType,
        companyName: item.companyName,
        payAmount: item.payAmount,
        payType: item.payType,
        vacancies: item.vacancies,
        urgency: "NORMAL",
        shift: item.shift,
        area: item.area,
        lat: lat,
        lng: lng,
        geohash: geohash,
        cell: cell,
        districtId: item.districtId,
        district: item.district,
        stateId: item.stateId,
        state: item.state,
        status: "open",
        applicationCount: 0,
        keywords: keywords,
        createdAt: Timestamp.fromMillis(jobCreatedAt),
        expiresAt: Timestamp.fromMillis(jobCreatedAt + JOB_LIFETIME_MS)
      };

      const detailsData = {
        employerId: "admin_dutype",
        description: item.description,
        addressText: `${item.companyName}, ${item.area}`,
        gender: item.gender,
        experienceRequired: item.experienceRequired,
        educationRequired: item.educationRequired
      };

      const contactData = {
        employerId: "admin_dutype",
        contactNumber: item.contactNumber
      };

      batch.set(db.collection("jobmetadata").doc(jobId), cardData);
      batch.set(db.collection("job_details").doc(jobId), detailsData);
      batch.set(db.collection("job_contacts").doc(jobId), contactData);
      batch.set(db.collection("jobs").doc(jobId), cardData);

      count++;
    }

    await batch.commit();
    console.log(`Committed chunk up to job ${count}/${newJobs.length}`);
  }

  console.log(`\n Successfully posted ${count} fresh, verified hyper-local jobs across Khammam, Telangana, AP, Karnataka & Tamil Nadu!`);
}

seedAllFreshJobs()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error("Failed to seed jobs:", e);
    process.exit(1);
  });
