async function seedTelanganaJobs() {
  console.log(" Starting Telangana Hyper-Local Jobs Seeding across all cities...");

  // Load scraped JobHai jobs from test-jobs.json if present to include real scraped jobs as well
  const scrapedJobsPath = resolve(__dirname, "output/test-jobs.json");
  const scrapedJobs = [];
  if (existsSync(scrapedJobsPath)) {
    try {
      const data = JSON.parse(readFileSync(scrapedJobsPath, "utf-8"));
      if (Array.isArray(data.jobs)) {
        for (const item of data.jobs) {
          if (item && item.meta && item.details && item.details.contactNumber) {
            scrapedJobs.push({
              title: item.meta.title || "Store Helper",
              companyName: item.meta.companyName || "Local Enterprise",
              category: "HELPER",
              employmentType: "FULL_TIME",
              payAmount: 16000,
              payType: "MONTHLY",
              vacancies: item.meta.vacancies || 2,
              shift: "DAY",
              area: item.meta.addressText || "Raniganj, Hyderabad",
              lat: item.meta.location?.lat || 17.385044,
              lng: item.meta.location?.lng || 78.486671,
              contactNumber: item.details.contactNumber,
              gender: item.details.gender || "ANY",
              experienceRequired: item.details.experienceRequired || "Fresher",
              educationRequired: item.details.educationRequired || "10th Pass",
              districtId: 508,
              district: "Hyderabad",
              description: item.details.description || "General helper and store operational duties."
            });
          }
        }
        console.log(` Loaded ${scrapedJobs.length} real scraped jobs from JobHai review cache.`);
      }
    } catch (e) {
      console.warn("Could not load scraped jobs file:", e.message);
    }
  }

  // Combine curated district hyper-local jobs + scraped real jobs
  const allJobsToSeed = [...TELANGANA_DISTRICT_JOBS, ...scrapedJobs];
  console.log(`Total jobs prepared for seeding: ${allJobsToSeed.length}`);

  const now = Date.now();
  const JOB_LIFETIME_MS = 30 * 24 * 60 * 60 * 1000;

  // Track unique keys to guarantee 0 duplicates
  const seenKeys = new Set();
  let count = 0;
  const CHUNK_SIZE = 40;

  for (let i = 0; i < allJobsToSeed.length; i += CHUNK_SIZE) {
    const chunk = allJobsToSeed.slice(i, i + CHUNK_SIZE);
    const batch = db.batch();

    for (let j = 0; j < chunk.length; j++) {
      const item = chunk[j];
      const dedupKey = `${item.contactNumber}_${item.title.toLowerCase().trim()}_${item.districtId}`;
      if (seenKeys.has(dedupKey)) {
        console.log(` Skipping duplicate: ${dedupKey}`);
        continue;
      }
      seenKeys.add(dedupKey);

      const citySlug = (item.district || "tg").toLowerCase().replace(/[^a-z0-9]/g, "");
      const catSlug = (item.category || "job").toLowerCase().replace(/[^a-z0-9]/g, "");
      const jobId = `tg_${citySlug}_${catSlug}_${i + j}_${Math.floor(1000 + Math.random() * 9000)}`;

      const lat = item.lat;
      const lng = item.lng;
      const geohash = encodeGeohash(lat, lng, 9);
      const cell = encodeGeohash(lat, lng, 5);
      const keywords = keywordsOf(item.title, item.companyName, item.area, item.district, "Telangana", item.category.replace(/_/g, " "));

      // Slight timestamp jitter (within last 12-24 hours) to simulate natural postings
      const jitterMs = (count % 36) * 35 * 60 * 1000;
      const jobCreatedAt = now - jitterMs;

      const cardData = {
        employerId: "admin_dutype",
        title: item.title,
        category: item.category,
        employmentType: item.employmentType,
        companyName: item.companyName,
        payAmount: item.payAmount,
        payType: item.payType,
        vacancies: item.vacancies,
        urgency: "NORMAL",
        shift: item.shift,
        area: item.area,
        lat: lat,
        lng: lng,
        geohash: geohash,
        cell: cell,
        districtId: item.districtId,
        district: item.district,
        stateId: 36,
        state: "Telangana",
        status: "open",
        applicationCount: 0,
        keywords: keywords,
        createdAt: Timestamp.fromMillis(jobCreatedAt),
        expiresAt: Timestamp.fromMillis(jobCreatedAt + JOB_LIFETIME_MS)
      };

      const detailsData = {
        employerId: "admin_dutype",
        description: item.description,
        addressText: `${item.companyName}, ${item.area}`,
        gender: item.gender,
        experienceRequired: item.experienceRequired,
        educationRequired: item.educationRequired
      };

      const contactData = {
        employerId: "admin_dutype",
        contactNumber: item.contactNumber
      };

      // Set in all 4 collections: jobmetadata, job_details, job_contacts, jobs
      batch.set(db.collection("jobmetadata").doc(jobId), cardData);
      batch.set(db.collection("job_details").doc(jobId), detailsData);
      batch.set(db.collection("job_contacts").doc(jobId), contactData);
      batch.set(db.collection("jobs").doc(jobId), cardData);

      count++;
    }

    await batch.commit();
    console.log(` Committed batch up to job ${count}/${allJobsToSeed.length}`);
  }

  console.log(`\n Successfully seeded ${count} real hyper-local Telangana jobs across jobmetadata, job_details, job_contacts & jobs!`);
}

seedTelanganaJobs()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error("Failed to seed jobs:", e);
    process.exit(1);
  });
